package CIET;
/*
 * relational operator
 * == Equal to
 * != not equal
 * > greater
 * < less than
 * >= greater than or equal to
 * <= less than or equal to
 */

public class Code6 {
	public static void main(String[] args) {
		byte a = 15;
		byte b = 2;
		System.out.println(a==b);
		System.out.println(a!=b);
		System.out.println(a>b);
		System.out.println(a<b);
		System.out.println(a<=b);
		System.out.println(a>=b);
	}
}
